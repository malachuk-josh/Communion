// Where the Treasury of David plans break a psalm into more than one day.
//
// A plan built on the Treasury is a psalm a day, read with what Spurgeon wrote
// on it. Most psalms make a sitting of a quarter of an hour that way — the
// middle of them is about 3,500 words of his — but a few run to two or three
// times that, and Psalm 119 to seventy thousand words, which is not a day of
// anything. So the long ones are spread over as many days as their length
// asks for, cut where one of his verse notes ends and the next begins, and
// Psalm 119 goes a stanza at a time: its twenty-two letters of eight verses
// each are the divisions the psalm makes itself.
//
// Read from public/treasury/19.json, so it follows whatever that file holds,
// and from the King James for how many verses each psalm has. Run again after
// rebuilding the Treasury: node scripts/build-treasury-plan.mjs
// Writes lib/treasuryParts.ts.

import { readFileSync, writeFileSync } from "fs";
import path from "path";

const ROOT = process.cwd();
const treasury = JSON.parse(
  readFileSync(path.join(ROOT, "public", "treasury", "19.json"), "utf8")
);
const kjv = JSON.parse(
  readFileSync(path.join(ROOT, "public", "bible", "kjv", "19.json"), "utf8")
);

/** About a quarter of an hour of Spurgeon: the length of an ordinary day. */
const DAY_WORDS = 4500;

const words = (s) => (s ? s.split(/\s+/).filter(Boolean).length : 0);
const lastVerse = (psalm) => kjv[String(psalm)].length;

const parts = {};
for (let psalm = 1; psalm <= 150; psalm++) {
  const entry = treasury[String(psalm)];
  if (!entry) continue;
  const end = lastVerse(psalm);

  if (psalm === 119) {
    parts[psalm] = Array.from({ length: 22 }, (_, i) => [i * 8 + 1, i * 8 + 8]);
    continue;
  }

  // the overview opens the psalm, so it counts toward the first day
  const notes = entry.verses.filter((v) => v.from >= 1);
  const sizes = notes.map((v) => words(v.text));
  const total = words(entry.overview) + sizes.reduce((a, b) => a + b, 0);
  const days = Math.max(1, Math.round(total / DAY_WORDS));
  if (days === 1 || notes.length < days) continue;

  // cut after the note that carries the running total past each day's share
  const cuts = [];
  let running = words(entry.overview);
  notes.forEach((note, i) => {
    running += sizes[i];
    const share = (total * (cuts.length + 1)) / days;
    if (cuts.length < days - 1 && running >= share && i < notes.length - 1) {
      cuts.push(notes[i + 1].from);
    }
  });
  const starts = [1, ...cuts];
  parts[psalm] = starts.map((from, i) => [
    from,
    i + 1 < starts.length ? starts[i + 1] - 1 : end,
  ]);
}

const rows = Object.entries(parts).map(
  ([psalm, list]) =>
    `  ${psalm}: [${list.map(([a, b]) => `[${a}, ${b}]`).join(", ")}],`
);
writeFileSync(
  path.join(ROOT, "lib", "treasuryParts.ts"),
  `// Generated by scripts/build-treasury-plan.mjs — do not edit by hand.\n` +
    `//\n` +
    `// The psalms that the Treasury of David plans spread over more than one\n` +
    `// day, and the verses each day covers. A psalm not listed is one day.\n\n` +
    `/** psalm → [first verse, last verse] for each of its days */\n` +
    `export const TREASURY_PARTS: Record<number, [number, number][]> = {\n` +
    rows.join("\n") +
    `\n};\n`
);

const extra = Object.values(parts).reduce((n, list) => n + list.length - 1, 0);
console.log(`split psalms : ${Object.keys(parts).length}`);
console.log(`days         : ${150 + extra} for the whole Psalter`);
